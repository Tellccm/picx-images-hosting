/* 在〈召唤兽·类别与元素〉末尾追加「类别 × 元素 → 物种名」推导表（重写版） */
import { readFileSync, writeFileSync } from 'node:fs';
const p = process.argv[2];
const wb = JSON.parse(readFileSync(p, 'utf8'));
const e = wb.entries.find((x) => String(x.comment).includes('类别与元素'));

const TABLE = `
# 六、类别 × 元素 → 物种名（推导表）
  下表给出命名的**方向**，不是穷举。可以自由造名，只要符合类别与元素。
  品阶影响命名的格调: 凡种更土，贵种以上更讲究。

  兽类
    无 → 家犬 / 野狗      火 → 焰犬 / 赤鬃狮    水 → 河獭
    风 → 疾狼             地 → 石熊 / 铁甲犀    雷 → 雷豹
    冰 → 霜狼             光 → 白鹿             暗 → 夜豺
  狐类
    无 → 赤狐             火 → 焰狐             水 → 水貂
    风 → 风狸             地 → 穴獾             雷 → 迅狸
    冰 → 雪狐             光 → 银狐             暗 → 影狐
  猫类
    无 → 狸猫             火 → 烬猫             水 → 渔猫
    风 → 轻猞             地 → 岩猫             雷 → 雷猁
    冰 → 霜猁             光 → 月猫             暗 → 墨猫
  鸟类
    无 → 灰鸽 / 渡鸦      火 → 焰鸦             水 → 鱼鹰
    风 → 风隼             地 → 石雉             雷 → 雷隼
    冰 → 雪枭             光 → 白鹤             暗 → 夜枭
  爬行类
    无 → 石蜥             火 → 炎蜥             水 → 水蛇
    风 → 细鳞             地 → 岩龙蜥           雷 → 电角蜥
    冰 → 冰蜥             光 → 玉蛇             暗 → 玄蟒
  虫类
    无 → 田螳             火 → 火蚁             水 → 水黾
    风 → 飞蝗             地 → 甲虫             雷 → 雷蜂
    冰 → 寒蛛             光 → 萤蜂             暗 → 毒蛛
  水生类
    无 → 河鲤             火 → 温泉鳐           水 → 潮汐鲸
    风 → 飞鱼             地 → 铁壳龟           雷 → 电鳗
    冰 → 冰鳐             光 → 银鳞             暗 → 深渊章
  异种类（这一类的组合本就少见，名字由现场定义）
    无 → 无名兽           火 → 灰烬行者         水 → 沉溺之物
    风 → 无定形           地 → 土偶             雷 → 焦痕
    冰 → 霜壳             光 → 白影             暗 → 影噬

  用法:
    · 例: 狐类 + 火 + 贵种 → 「焰狐」
    · 例: 鸟类 + 风 + 良种 → 「风隼」
    · 例: 兽类 + 无 + 凡种 → 「家犬」
    · 表里没有的组合，当场给一个符合逻辑的名字，之后保持一致

# 七、命名风格参考
  平民家里 —— 土名。灰耳、阿炭、黑豆、老六、铁蛋。不带姓
  商贾与富户 —— 稍讲究。铜铃、青眼、小满。有时用器物或节令命名
  贵族 —— 正式名。多与元素或血统相关，如「霜牙」「炎鬃」「银翼」
  学院登记 —— 用「品阶 + 类别 + 元素」，如「贵种·狐类·火」
  异种 —— 常常没有名字。灰烬所的学生管它们叫「那个东西」

# 八、名字由谁定
  · 名字由 <user> 自己取。开局面板里有一栏就是为这个准备的
  · 觉醒当场通常来不及取名，多数人几天后才定下来
  · 名字一旦定下就跟着它一辈子。**不要中途改名**，除非有明确的剧情理由
  · 若 <user> 一直没取，就写「未命名」。**不要替 <user> 擅自取一个然后当既定事实**
`;

let c = e.content.replace(/<\/召唤兽类别与元素>\s*$/, '');
c = c.trimEnd() + '\n' + TABLE + '</召唤兽类别与元素>\n';
e.content = c;

writeFileSync(p, JSON.stringify(wb, null, 2) + '\n', 'utf8');
console.log('条目长度 ' + e.content.length);
console.log('闭合标签数 ' + (e.content.match(/<\/召唤兽类别与元素>/g) || []).length);
console.log('含 electric 残留 = ' + e.content.includes('electric'));
